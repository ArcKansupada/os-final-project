#pragma once

#include <cstdint>

/*
 * The user-mode state of a process, saved on entry to the kernel (see syscallHandler_).
 *
 */
struct UserContext {
  uint64_t rax, rbx, rcx, rdx, rsi, rdi, rbp;
  uint64_t r8, r9, r10, r11, r12, r13, r14, r15;
  uint64_t rip, rsp, rflags;
  uint64_t fs_base, gs_base;
  alignas(16) uint8_t fpu[512]; // x87/SSE state, fxsave format

  UserContext();
};



#include <stdio.h>
#include <string.h>
#include <unistd.h>

int puts(const char *s) {
  const ssize_t n = write(1, s, strlen(s));
  if (n < 0 || write(1, "\n", 1) < 0) {
    return EOF; // write set errno
  }
  return (int)n + 1;
}
